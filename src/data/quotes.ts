/** Get a random quote, optionally filtered by theme */
export function getRandomQuote(theme?: string): Quote {
  const pool = theme ? quotes.filter((q) => q.themes.includes(theme as never)) : quotes
  const list = pool.length > 0 ? pool : quotes
  return list[Math.floor(Math.random() * list.length)]
}

/** Get the quote of the day based on date (deterministic) */
export function getQuoteOfTheDay(dateStr: string): Quote {
  const hash = dateStr.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0)
  return quotes[hash % quotes.length]
}
